// Shared helpers for the static-page generators in scripts/.

/** Escape text for HTML element content and double-quoted attributes. */
export function escapeHtml(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}
